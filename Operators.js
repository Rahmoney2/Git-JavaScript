// Comparison Operators
let r = 10;
let s = 5;
console.log(r == s); // equal to
console.log(r != s); // not equal to
console.log(r > s); // greater than
console.log(r < s); // less than
console.log(r >= s); // greater than or equal to
console.log(r <= s); // less than or equal to

// Logical Operators
let t = true;
let h = false;
console.log(t && h); // AND
console.log(t || h); // OR
console.log(!t); // NOT

// Bitwise Operators
let i = 5;
let j = 3;
console.log(i & j); // AND
console.log(i | j); // OR
console.log(i ^ j); // XOR
console.log(~i); // NOT
console.log(i << 1); // Left shift
console.log(i >> 1); // Right shift
